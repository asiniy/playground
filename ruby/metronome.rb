class String
  def colorize(color_code)
    "\e[#{color_code}m#{self}\e[0m"
  end

  def green
    colorize(32)
  end

  def blue
    colorize(34)
  end
end

def ascii_countdown(period, color)
  puts `clear`

  i = period
  while i > 0
    number = NUMBERS.fetch(i)
    puts (color == :green) ? number.green : number.blue
    i -= 1
    sleep 1
  end
end

loop do
  ascii_countdown(period, :green)
  ascii_countdown(period, :blue)
end
